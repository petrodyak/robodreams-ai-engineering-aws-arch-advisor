"""`evals/agent/TASKS.md`: the agent task set as a table to read and review (Task 25.1).

Generated from `evals/agent/tasks.jsonl`, never edited by hand; a test fails when it is stale.

    uv run python -m evals.agent.tasks_md
"""

import json
from pathlib import Path

from evals.agent.run import TASKS, load_tasks

OUT = Path("evals/agent/TASKS.md")


def _check(c: dict) -> str:
    rest = {k: v for k, v in c.items() if k != "type"}
    return f"`{c['type']}`" + (
        f" {json.dumps(rest, ensure_ascii=False)}" if rest else ""
    )


def _script(task: dict) -> str:
    parts = []
    for i, session in enumerate(task["sessions"]):
        if i:
            parts.append("*new session*")
        for step in session:
            if "command" in step:
                parts.append(f"`{step['command']}`")
            else:
                confirm = f" (confirm: {step['confirm']})" if "confirm" in step else ""
                parts.append(step["user"] + confirm)
    return "<br>".join(parts).replace("|", "\\|")


def render(tasks: list[dict]) -> str:
    lines = [
        "# Agent task set (HW 3)",
        "",
        "Generated by `uv run python -m evals.agent.tasks_md` from `evals/agent/tasks.jsonl`; do not edit.",
        "Spec §13. Every eval task also indexes the adversarial overlay (spec §10).",
        "",
        "| id | kind | faults / autonomy / limits | conversation | precondition | checks |",
        "|---|---|---|---|---|---|",
    ]
    for t in tasks:
        setup = (
            ", ".join(
                x
                for x in (
                    f"faults `{t['faults']}`" if t["faults"] else "",
                    f"autonomy `{t['autonomy']}`" if t["autonomy"] != "confirm" else "",
                    f"limits {json.dumps(t['limits'])}" if t.get("limits") else "",
                )
                if x
            )
            or "—"
        )
        pre = (
            "<br>".join(_check(c) for c in t["precondition"]).replace("|", "\\|") or "—"
        )
        checks = "<br>".join(_check(c) for c in t["checks"]).replace("|", "\\|")
        lines.append(
            f"| {t['id']} | {t['kind']} | {setup} | {_script(t)} | {pre} | {checks} |"
        )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(load_tasks(TASKS)), encoding="utf-8")
    print(f"wrote {OUT}")
