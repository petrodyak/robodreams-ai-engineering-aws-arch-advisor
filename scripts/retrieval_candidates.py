"""Labelling sheet for the retrieval eval: evals/labels/retrieval_candidates.md (plan Task 17.3).

For every answerable item it lists the union of the vector top 10 and the BM25 top 10 over the
structure chunks. Showing both lists keeps the labels from favouring the method that produced the
sheet. Petro ticks the relevant rows (`[x]`); the ticked ids go into `relevant_chunk_ids`.

    uv run python -m scripts.retrieval_candidates
"""

from pathlib import Path

from evals.testset import load_testset
from src.rag.config import load_config
from src.rag.index import Index, default_embed_fn, load_chunks
from src.rag.search import search

OUT = Path("evals/labels/retrieval_candidates.md")
TOP = 10
PREVIEW = 200


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def main() -> None:
    cfg = load_config()
    chunks = load_chunks(Path("data/rag/chunks.jsonl"))
    index = Index(chunks, embed_fn=default_embed_fn(cfg.embed_model))

    lines = [
        "# Retrieval labelling sheet",
        "",
        "Generated by `scripts/retrieval_candidates.py`: per question, the union of the vector top 10",
        "and the BM25 top 10 over `data/rag/chunks.jsonl`. Tick `[x]` every chunk that answers the",
        "question, or a necessary part of it. The ticked ids become `relevant_chunk_ids`.",
        "",
    ]
    for it in load_testset():
        if not it.answerable:
            continue
        vec = [h.chunk for h in search(index, it.question, k=TOP, mode="vector")]
        bm = [h.chunk for h in search(index, it.question, k=TOP, mode="bm25")]
        vec_rank = {c.chunk_id: r for r, c in enumerate(vec, 1)}
        bm_rank = {c.chunk_id: r for r, c in enumerate(bm, 1)}
        union = list({c.chunk_id: c for c in vec + bm}.values())
        sources = "; ".join(f"{s.doc_id}: {s.section}" for s in it.expected_sources)
        lines += [
            f"## {it.id} ({it.kind})",
            "",
            f"**Q:** {it.question}",
            "",
            f"**Expected source:** {sources}",
            "",
            "| ok | chunk_id | vec | bm25 | section path | text |",
            "|---|---|---|---|---|---|",
        ]
        for c in union:
            lines.append(
                f"| [ ] | `{c.chunk_id}` | {vec_rank.get(c.chunk_id, '-')} "
                f"| {bm_rank.get(c.chunk_id, '-')} | {_cell(' > '.join(c.section_path))} "
                f"| {_cell(c.text[:PREVIEW])} |"
            )
        lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"written {OUT}")


if __name__ == "__main__":
    main()
